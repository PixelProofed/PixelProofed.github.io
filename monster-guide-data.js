function inferMonsterRarity(origin) {
  var value = String(origin || "").toLowerCase();

  if (value.indexOf("third stage") !== -1) {
    return "Third Stage";
  }

  if (value.indexOf("second stage") !== -1) {
    return "Second Stage";
  }

  if (value.indexOf("first stage") !== -1) {
    return "First Stage";
  }

  return "Origin";
}

function normalizeMonsterTags(tags) {
  if (!Array.isArray(tags) || !tags.length) {
    return [];
  }

  return tags;
}

function isPureEvolutionOrigin(origin) {
  var value = String(origin || "").toLowerCase();

  return (
    value.indexOf("evolution") !== -1 &&
    value.indexOf("born") === -1 &&
    value.indexOf("spawn") === -1 &&
    value.indexOf("mana") === -1
  );
}

function stripLeadingInheritedTraitLines(value) {
  var lines = String(value || "---").split(/\r?\n/);

  while (lines.length && /^\s*-\s\*\*[^*]+\*\*\s*$/.test(lines[0])) {
    lines.shift();
  }

  return lines.join("\n").trim() || "---";
}

function getInheritedTraitLines(lineSlug, monsterName) {
  var treeData = window.evolutionTreeData || [];
  var lineIndex;

  for (lineIndex = 0; lineIndex < treeData.length; lineIndex += 1) {
    var line = treeData[lineIndex];
    var pathIndex;
    var grouped = [];

    if (line.slug !== lineSlug) {
      continue;
    }

    for (pathIndex = 0; pathIndex < line.paths.length; pathIndex += 1) {
      var path = line.paths[pathIndex];
      var monsterIndex = path.indexOf(monsterName);

      if (monsterIndex <= 0) {
        continue;
      }

      path.slice(0, monsterIndex).forEach(function (name, depth) {
        var stage = grouped[depth] || [];

        if (stage.indexOf(name) === -1) {
          stage.push(name);
        }

        grouped[depth] = stage;
      });
    }

    if (!grouped.length) {
      return [];
    }

    return [
      grouped
        .map(function (stageNames) {
          if (!stageNames || !stageNames.length) {
            return "";
          }

          if (stageNames.length === 1) {
            return stageNames[0];
          }

          if (stageNames.length === 2) {
            return stageNames[0] + " or " + stageNames[1];
          }

          return (
            stageNames.slice(0, -1).join(", ") +
            ", or " +
            stageNames[stageNames.length - 1]
          );
        })
        .filter(Boolean)
        .join(" / "),
    ];
  }

  return [];
}

function formatInheritedTraitPrefix(lines) {
  if (!lines.length) {
    return "";
  }

  return lines
    .map(function (line) {
      return "- **Traits From " + line + "**";
    })
    .join("\n");
}

function buildTraitsText(lineSlug, monster) {
  var baseTraits = stripLeadingInheritedTraitLines(monster[5] || "---");
  var inherited;

  if (!isPureEvolutionOrigin(monster[1])) {
    return baseTraits;
  }

  inherited = getInheritedTraitLines(lineSlug, monster[0]);

  if (!inherited.length) {
    return baseTraits;
  }

  if (!baseTraits || baseTraits === "---") {
    return formatInheritedTraitPrefix(inherited);
  }

  return formatInheritedTraitPrefix(inherited) + "\n" + baseTraits;
}

window.monsterGuideData = window.monsterGuideData.map(function (line) {
  return {
    slug: line.slug,
    name: line.name,
    monsters: line.monsters.map(function (monster) {
      return {
        name: monster[0],
        origin: monster[1],
        rarity: inferMonsterRarity(monster[1]),
        commonality: monster[2],
        tags: normalizeMonsterTags(monster[3]),
        tagsText: normalizeMonsterTags(monster[3]).length
          ? normalizeMonsterTags(monster[3]).join(", ")
          : "---",
        description: monster[4] || "---",
        traits: buildTraitsText(line.slug, monster),
      };
    }),
  };
});
